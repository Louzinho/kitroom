"""Writes docs/screenshots/3-transactions/db-proof.md: raw rows before and after a
successful checkout and a failed one, read directly from MySQL and MongoDB."""
from pathlib import Path

import pymysql

from app import create_app
from app.config import Config
from app.db import connect_mysql, mongo

OUT = Path(__file__).resolve().parent.parent / "docs" / "screenshots" / "3-transactions" / "db-proof.md"
HEADERS = {"X-Requested-With": "KitRoom"}


def table(rows):
    if not rows:
        return "(no rows)\n"
    cols = list(rows[0])
    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "".join("| " + " | ".join(str(r[c]) for c in cols) + " |\n" for r in rows)


def snapshot(a, b, admin_id):
    conn = connect_mysql(Config)
    with conn.cursor() as cur:
        cur.execute("SELECT product_id, title, stock_quantity FROM products WHERE product_id IN (%s,%s)", (a, b))
        products = cur.fetchall()
        cur.execute("""SELECT COUNT(*) AS orders_rows, (SELECT COUNT(*) FROM order_items) AS order_items_rows,
                       (SELECT COUNT(*) FROM sync_outbox) AS outbox_rows FROM orders""")
        counts = cur.fetchall()
    conn.close()
    db = mongo(Config)
    cart = db.shopping_carts.find_one({"userId": admin_id}) or {}
    docs = [{"shopping_carts lines": len(cart.get("items", [])),
             "order_placed logs": db.user_activity_logs.count_documents({"userId": admin_id, "action_type": "order_placed"}),
             "order alerts": db.user_notifications.count_documents({"userId": admin_id, "kind": "order"})}]
    return ("**MySQL `products`**\n\n" + table(products) + "\n**MySQL row counts**\n\n" + table(counts)
            + "\n**MongoDB**\n\n" + table(docs))


def main():
    app = create_app()
    c = app.test_client()
    r = c.post("/api/auth/login", headers=HEADERS,
               json={"email": "admin@kitroom.test", "password": "KitRoom2026"})
    admin_id = r.get_json()["user_id"]
    with app.app_context():
        items = c.get("/api/products?per_page=100&sort=title").get_json()["items"]
        a, b = [p["product_id"] for p in items if p["stock_quantity"] >= 3][:2]
        md = ["# Raw database state before and after\n\n"
              "Generated by `scripts/db_proof.py` from direct queries, not from the app's own screens.\n"]
        for scenario, title in (("success", "Successful checkout"),
                                ("after_order", "Failed checkout: crash after the order row was inserted")):
            md.append(f"\n## {title}\n\n### Before\n\n{snapshot(a, b, admin_id)}")
            result = c.post("/api/admin/lab/run", headers=HEADERS,
                            json={"scenario": scenario, "product_a": a, "product_b": b}).get_json()
            md.append(f"\n### After\n\n{snapshot(a, b, admin_id)}")
            md.append("\n### Statements reached\n\n" + "".join(
                f"- {'ok' if s['ok'] else 'FAILED'}: {s['step']}. {s['detail']}\n" for s in result["trace"]))
    OUT.write_text("".join(md), encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
